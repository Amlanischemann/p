function setLanguage(lang){
  if(!translations[lang]) lang="en";
  document.documentElement.lang=lang;
  document.documentElement.dir=lang==="ar"?"rtl":"ltr";
  document.querySelectorAll("[data-i18n]").forEach(el=>{const v=translations[lang][el.dataset.i18n];if(v)el.textContent=v});
  document.querySelectorAll("[data-lang]").forEach(btn=>{const selected=btn.dataset.lang===lang;btn.setAttribute("aria-pressed",String(selected));btn.classList.toggle("selected",selected)});
  try{localStorage.setItem("pharmed-lang",lang)}catch(e){}
}
document.addEventListener("DOMContentLoaded",()=>{
  let initial="en";try{initial=localStorage.getItem("pharmed-lang")||"en"}catch(e){}
  setLanguage(initial);
  document.querySelectorAll("[data-lang]").forEach(btn=>btn.addEventListener("click",()=>setLanguage(btn.dataset.lang)));
});
